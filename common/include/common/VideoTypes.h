#pragma once
// =============================================================================
// ClassroomMonitor — Video Types
//
// Типы и параметры видеокодирования.
// =============================================================================

#include <cstdint>
#include <vector>

namespace cm {
namespace video {

// =============================================================================
// Параметры кодирования
// =============================================================================

constexpr uint32_t DEFAULT_BITRATE     = 2000000;   // 2 Mbps
constexpr uint32_t MIN_BITRATE         = 500000;    // 500 Kbps (минимальное качество)
constexpr uint32_t MAX_BITRATE         = 8000000;   // 8 Mbps (максимальное качество)
constexpr uint32_t IFRAME_INTERVAL     = 30;         // I-frame каждые 30 кадров (2 сек при 15fps)

// =============================================================================
// Типы кадров
// =============================================================================

enum class FrameType : uint8_t {
    I_FRAME = 0,    // Ключевой кадр (полный)
    P_FRAME = 1,    // Дельта-кадр (различия)
};

// =============================================================================
// Сырой кадр (до кодирования)
// =============================================================================

struct RawFrame {
    std::vector<uint8_t> pixels;    // BGRA пиксели
    uint32_t width  = 0;
    uint32_t height = 0;
    uint32_t stride = 0;            // Шаг строки в байтах
    uint64_t timestamp = 0;         // Микросекунды
};

// =============================================================================
// Закодированный кадр (после H.264)
// =============================================================================

struct EncodedFrame {
    std::vector<uint8_t> data;      // H.264 NAL units
    FrameType type = FrameType::I_FRAME;
    uint32_t  width  = 0;
    uint32_t  height = 0;
    uint64_t  timestamp = 0;
};

// =============================================================================
// Параметры кодека
// =============================================================================

struct EncoderConfig {
    uint32_t width    = 1920;
    uint32_t height   = 1080;
    uint32_t fps      = 30;
    uint32_t bitrate  = DEFAULT_BITRATE;
    uint32_t iFrameInterval = 60; // 2 сек при 30fps
};

} // namespace video

} // namespace cm
